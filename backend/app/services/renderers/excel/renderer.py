from dataclasses import dataclass
from datetime import datetime, timezone
from hashlib import sha256
import os
from pathlib import Path
from uuid import uuid4

import xlsxwriter

from app.services.renderers.excel.contracts import (
    ComputedColumn,
    DataColumn,
    DataSheet,
    SummarySheet,
    WorkbookPlan,
    workbook_plan_sha256,
)
from app.services.renderers.excel.formulas import (
    comparison_formula,
    rank_formula,
    summary_formula,
)
from app.services.renderers.excel.templates import ExcelTemplate, get_excel_template


@dataclass(frozen=True)
class RenderedWorkbook:
    path: Path
    sha256: str
    byte_size: int
    plan_sha256: str
    schema_version: str
    renderer_version: str
    template_code: str
    template_version: str
    sheet_count: int
    generated_cell_count: int


@dataclass(frozen=True)
class _RenderedData:
    sheet: DataSheet
    column_indexes: dict[str, int]
    values: dict[str, tuple]


class ExcelRendererError(RuntimeError):
    pass


class ExcelRenderer:
    def render(
        self, plan: WorkbookPlan | dict, destination: str | Path
    ) -> RenderedWorkbook:
        validated = (
            plan
            if isinstance(plan, WorkbookPlan)
            else WorkbookPlan.validate_for_renderer(plan)
        )
        output_path = Path(destination).resolve()
        if output_path.exists():
            raise ExcelRendererError("workbook_output_already_exists")
        if not output_path.parent.is_dir():
            raise ExcelRendererError("workbook_output_directory_missing")
        temporary = output_path.parent / f".{output_path.name}.{uuid4().hex}.tmp"
        plan_checksum = workbook_plan_sha256(validated)
        template = get_excel_template(
            validated.template.code, validated.template.version
        )
        try:
            self._write_workbook(validated, template, plan_checksum, temporary)
            try:
                os.link(temporary, output_path)
            except FileExistsError as exception:
                raise ExcelRendererError(
                    "workbook_output_already_exists"
                ) from exception
            temporary.unlink()
        except Exception:
            temporary.unlink(missing_ok=True)
            raise
        digest = self._sha256_file(output_path)
        return RenderedWorkbook(
            path=output_path,
            sha256=digest,
            byte_size=output_path.stat().st_size,
            plan_sha256=plan_checksum,
            schema_version=validated.schema_version,
            renderer_version=validated.renderer_version,
            template_code=validated.template.code,
            template_version=validated.template.version,
            sheet_count=len(validated.sheets),
            generated_cell_count=sum(
                sheet.generated_cell_count for sheet in validated.sheets
            ),
        )

    def _write_workbook(
        self,
        plan: WorkbookPlan,
        template: ExcelTemplate,
        plan_checksum: str,
        destination: Path,
    ) -> None:
        workbook = xlsxwriter.Workbook(
            str(destination),
            {
                "constant_memory": True,
                "strings_to_formulas": False,
                "strings_to_urls": False,
            },
        )
        workbook.set_properties(
            {
                "title": plan.metadata.title,
                "subject": plan.metadata.subject,
                "author": plan.metadata.author,
                "company": plan.metadata.company,
                "comments": "Generated by Office AI deterministic Excel Renderer",
                "created": datetime(2000, 1, 1, tzinfo=timezone.utc),
            }
        )
        workbook.set_custom_property("OfficeAIPlanSHA256", plan_checksum, "text")
        workbook.set_custom_property(
            "OfficeAIRendererVersion", plan.renderer_version, "text"
        )
        workbook.set_custom_property(
            "OfficeAITemplate",
            f"{plan.template.code}@{plan.template.version}",
            "text",
        )
        formats = self._build_formats(workbook, template)
        rendered_data: dict[str, _RenderedData] = {}
        try:
            for sheet in plan.sheets:
                if isinstance(sheet, DataSheet):
                    rendered_data[sheet.name] = self._write_data_sheet(
                        workbook, sheet, template, formats
                    )
            for sheet in plan.sheets:
                if isinstance(sheet, SummarySheet):
                    self._write_summary_sheet(
                        workbook, sheet, template, formats, rendered_data
                    )
        finally:
            workbook.close()

    def _write_data_sheet(
        self,
        workbook,
        sheet: DataSheet,
        template: ExcelTemplate,
        formats: dict,
    ) -> _RenderedData:
        worksheet = workbook.add_worksheet(sheet.name)
        worksheet.set_tab_color(template.tab_color)
        all_columns: list[DataColumn | ComputedColumn] = [
            *sheet.columns,
            *sheet.computed_columns,
        ]
        column_indexes = {column.key: index for index, column in enumerate(all_columns)}
        worksheet.merge_range(
            0, 0, 0, len(all_columns) - 1, sheet.title, formats["title"]
        )
        worksheet.set_row(0, 24)
        for index, column in enumerate(all_columns):
            worksheet.write_string(1, index, column.header, formats["header"])
            worksheet.set_column(index, index, 16 if index else 18)

        values: dict[str, list] = {column.key: [] for column in all_columns}
        raw_values = {
            column.key: [row[column.key] for row in sheet.rows]
            for column in sheet.columns
        }
        first_data_row_number = 3
        last_data_row_number = len(sheet.rows) + 2
        for row_index, row in enumerate(sheet.rows):
            excel_row = row_index + 2
            excel_row_number = excel_row + 1
            for column in sheet.columns:
                value = row[column.key]
                values[column.key].append(value)
                self._write_value(
                    worksheet,
                    excel_row,
                    column_indexes[column.key],
                    value,
                    formats[self._format_name(column.value_type)],
                )
            numeric_row = {
                key: value
                for key, value in row.items()
                if isinstance(value, (int, float)) and not isinstance(value, bool)
            }
            for column in sheet.computed_columns:
                calculation = column.calculation
                if calculation.kind in {"yoy", "mom"}:
                    formula, cached = comparison_formula(
                        calculation,
                        excel_row_number,
                        column_indexes,
                        numeric_row,
                    )
                else:
                    formula, cached = rank_formula(
                        calculation,
                        excel_row_number,
                        first_data_row_number,
                        last_data_row_number,
                        column_indexes,
                        raw_values[calculation.source_column],
                        row_index,
                    )
                values[column.key].append(cached)
                worksheet.write_formula(
                    excel_row,
                    column_indexes[column.key],
                    formula,
                    formats[self._format_name(column.value_type)],
                    cached,
                )

        self._apply_data_features(
            worksheet,
            sheet,
            column_indexes,
            formats,
            last_data_row_number - 1,
        )
        return _RenderedData(
            sheet=sheet,
            column_indexes=column_indexes,
            values={key: tuple(items) for key, items in values.items()},
        )

    def _write_summary_sheet(
        self,
        workbook,
        sheet: SummarySheet,
        template: ExcelTemplate,
        formats: dict,
        rendered_data: dict[str, _RenderedData],
    ) -> None:
        worksheet = workbook.add_worksheet(sheet.name)
        worksheet.set_tab_color(template.tab_color)
        worksheet.merge_range(0, 0, 0, 1, sheet.title, formats["title"])
        worksheet.set_row(0, 24)
        worksheet.write_row(1, 0, ["指标", "值"], formats["header"])
        worksheet.set_column(0, 0, 22)
        worksheet.set_column(1, 1, 18)
        for metric_index, metric in enumerate(sheet.metrics, start=2):
            source = rendered_data[metric.calculation.source_sheet]
            source_column_index = source.column_indexes[
                metric.calculation.source_column
            ]
            source_values = source.values[metric.calculation.source_column]
            formula, cached = summary_formula(
                metric.calculation,
                source_column_index,
                3,
                len(source.sheet.rows) + 2,
                source_values,
            )
            worksheet.write_string(
                metric_index, 0, metric.label, formats["metric_label"]
            )
            worksheet.write_formula(
                metric_index,
                1,
                formula,
                formats["metric_value"],
                cached,
            )
        for chart_plan in sheet.charts:
            source = rendered_data[chart_plan.source_sheet]
            chart = workbook.add_chart({"type": chart_plan.chart_type})
            first_row = 2
            last_row = len(source.sheet.rows) + 1
            category_column = source.column_indexes[chart_plan.categories_column]
            for value_column in chart_plan.value_columns:
                value_column_index = source.column_indexes[value_column]
                chart.add_series(
                    {
                        "name": [
                            source.sheet.name,
                            1,
                            value_column_index,
                        ],
                        "categories": [
                            source.sheet.name,
                            first_row,
                            category_column,
                            last_row,
                            category_column,
                        ],
                        "values": [
                            source.sheet.name,
                            first_row,
                            value_column_index,
                            last_row,
                            value_column_index,
                        ],
                    }
                )
            chart.set_title({"name": chart_plan.title})
            chart.set_style(template.chart_style)
            chart.set_legend({"position": "bottom"})
            worksheet.insert_chart(chart_plan.anchor, chart)
        self._apply_sheet_settings(
            worksheet,
            sheet.freeze_panes.row,
            sheet.freeze_panes.column,
            sheet.print_settings,
            max(2 + len(sheet.metrics), 20),
            7,
        )

    @staticmethod
    def _build_formats(workbook, template: ExcelTemplate) -> dict:
        return {
            "title": workbook.add_format(template.title_format),
            "header": workbook.add_format(template.header_format),
            "text": workbook.add_format(template.text_format),
            "number": workbook.add_format(template.number_format),
            "integer": workbook.add_format(template.integer_format),
            "percent": workbook.add_format(template.percent_format),
            "boolean": workbook.add_format(template.text_format),
            "metric_label": workbook.add_format(template.metric_label_format),
            "metric_value": workbook.add_format(template.metric_value_format),
            "negative": workbook.add_format(template.negative_format),
        }

    @staticmethod
    def _write_value(worksheet, row: int, column: int, value, cell_format) -> None:
        if value is None:
            worksheet.write_blank(row, column, None, cell_format)
        elif isinstance(value, bool):
            worksheet.write_boolean(row, column, value, cell_format)
        elif isinstance(value, (int, float)):
            worksheet.write_number(row, column, value, cell_format)
        else:
            worksheet.write_string(row, column, value, cell_format)

    def _apply_data_features(
        self,
        worksheet,
        sheet: DataSheet,
        column_indexes: dict[str, int],
        formats: dict,
        last_row: int,
    ) -> None:
        criteria = {
            "less_than": "<",
            "less_than_or_equal_to": "<=",
            "greater_than": ">",
            "greater_than_or_equal_to": ">=",
            "equal_to": "==",
            "not_equal_to": "!=",
        }
        for rule in sheet.conditional_formats:
            column = column_indexes[rule.target_column]
            options = {"type": rule.kind}
            if rule.kind == "cell":
                options.update(
                    {
                        "criteria": criteria[rule.operator],
                        "value": rule.value,
                        "format": formats["negative"],
                    }
                )
            worksheet.conditional_format(2, column, last_row, column, options)
        for validation in sheet.data_validations:
            column = column_indexes[validation.target_column]
            worksheet.data_validation(
                2,
                column,
                last_row,
                column,
                {"validate": "list", "source": validation.values},
            )
        self._apply_sheet_settings(
            worksheet,
            sheet.freeze_panes.row,
            sheet.freeze_panes.column,
            sheet.print_settings,
            last_row,
            len(column_indexes) - 1,
        )

    @staticmethod
    def _apply_sheet_settings(
        worksheet,
        freeze_row: int,
        freeze_column: int,
        print_settings,
        last_row: int,
        last_column: int,
    ) -> None:
        worksheet.freeze_panes(freeze_row, freeze_column)
        worksheet.hide_gridlines(2)
        worksheet.center_horizontally()
        if print_settings.orientation == "landscape":
            worksheet.set_landscape()
        else:
            worksheet.set_portrait()
        worksheet.fit_to_pages(
            print_settings.fit_width,
            print_settings.fit_height,
        )
        worksheet.print_area(0, 0, last_row, last_column)
        if print_settings.repeat_header:
            worksheet.repeat_rows(1, 1)

    @staticmethod
    def _format_name(value_type: str) -> str:
        return {
            "text": "text",
            "number": "number",
            "integer": "integer",
            "boolean": "boolean",
            "percent": "percent",
        }[value_type]

    @staticmethod
    def _sha256_file(path: Path) -> str:
        digest = sha256()
        with path.open("rb") as handle:
            while chunk := handle.read(1024 * 1024):
                digest.update(chunk)
        return digest.hexdigest()
